CREATE TABLE MOB_BELI_LAMA (
  NO_TRANSAKSI VARCHAR2(30) PRIMARY KEY,
  PURCHASE_ID NUMBER NOT NULL UNIQUE REFERENCES POS_PEMBELIAN(PURCHASE_ID),
  TANGGAL_REKONSILIASI DATE NOT NULL,
  REVISI NUMBER(10) DEFAULT 1 NOT NULL CHECK (REVISI > 0)
)
/
CREATE TABLE MOB_BELI_LAMA_SALDO (
  NO_TRANSAKSI VARCHAR2(30) NOT NULL REFERENCES MOB_BELI_LAMA(NO_TRANSAKSI),
  REVISI NUMBER(10) NOT NULL CHECK (REVISI > 0),
  SEN NUMBER(18,0) NOT NULL CHECK (SEN >= 0),
  JATUH_TEMPO DATE,
  REFERENSI VARCHAR2(250 CHAR) NOT NULL,
  ALASAN VARCHAR2(250 CHAR),
  USER_ID NUMBER NOT NULL REFERENCES MOB_USER(USER_ID),
  USER_NAMA VARCHAR2(100) NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_MOB_BELI_LAMA_SALDO PRIMARY KEY (NO_TRANSAKSI, REVISI)
)
/
CREATE TABLE MOB_BELI_LAMA_BAYAR (
  ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  NO_TRANSAKSI VARCHAR2(30) NOT NULL REFERENCES MOB_BELI_LAMA(NO_TRANSAKSI),
  TANGGAL DATE NOT NULL,
  METODE VARCHAR2(10) NOT NULL CHECK (METODE IN ('TUNAI','TRANSFER','LAINNYA')),
  REFERENSI VARCHAR2(100 CHAR),
  SEN NUMBER(18,0) NOT NULL,
  BALIK_ID NUMBER UNIQUE REFERENCES MOB_BELI_LAMA_BAYAR(ID),
  ALASAN VARCHAR2(250 CHAR),
  USER_ID NUMBER NOT NULL REFERENCES MOB_USER(USER_ID),
  USER_NAMA VARCHAR2(100) NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT CK_MOB_BELI_LAMA_BAYAR CHECK (
    (BALIK_ID IS NULL AND SEN > 0) OR
    (BALIK_ID IS NOT NULL AND SEN < 0 AND ALASAN IS NOT NULL)
  )
)
/
CREATE INDEX IX_MOB_BELI_LAMA_BAYAR_NO ON MOB_BELI_LAMA_BAYAR(NO_TRANSAKSI, ID)
