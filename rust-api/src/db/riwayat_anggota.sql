-- Jalankan terpisah setelah DDL disetujui. Aktifkan POS_WEB_MEMBER_HISTORY setelah verifikasi.
CREATE TABLE MOB_ANGGOTA_RIWAYAT (
  ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  ID_PELANGGAN NUMBER NOT NULL,
  NIK VARCHAR2(20 BYTE),
  NAMA VARCHAR2(50 BYTE),
  JENIS VARCHAR2(20 BYTE) NOT NULL
    CHECK (JENIS IN ('MASUK','MUTASI','NONAKTIF','AKTIF','BERHENTI','GABUNG_KEMBALI')),
  ADMIN_ID NUMBER NOT NULL,
  ADMIN_NAMA VARCHAR2(100 CHAR) NOT NULL,
  ALASAN VARCHAR2(500 BYTE) NOT NULL,
  UNIT_DARI VARCHAR2(20 BYTE),
  UNIT_KE VARCHAR2(20 BYTE),
  STATUS_DARI VARCHAR2(20 BYTE),
  STATUS_KE VARCHAR2(20 BYTE),
  AKTIF_DARI VARCHAR2(1 BYTE),
  AKTIF_KE VARCHAR2(1 BYTE),
  ANGGOTA_DARI VARCHAR2(1 BYTE),
  ANGGOTA_KE VARCHAR2(1 BYTE),
  WAKTU TIMESTAMP NOT NULL
);

CREATE INDEX IX_MOB_ANGGOTA_RIWAYAT_WAKTU ON MOB_ANGGOTA_RIWAYAT (WAKTU, ID);
CREATE INDEX IX_MOB_ANGGOTA_RIWAYAT_ANGGOTA ON MOB_ANGGOTA_RIWAYAT (ID_PELANGGAN, ID);
