CREATE TABLE MOB_KAS_AKUN (
  ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  KODE VARCHAR2(20) NOT NULL UNIQUE,
  NAMA VARCHAR2(100 CHAR) NOT NULL,
  JENIS VARCHAR2(4) NOT NULL CHECK (JENIS IN ('KAS','BANK')),
  NO_REKENING VARCHAR2(50),
  ATAS_NAMA VARCHAR2(100 CHAR),
  SALDO_AWAL NUMBER(16,0) DEFAULT 0 NOT NULL,
  TGL_SALDO_AWAL DATE NOT NULL,
  DEFAULT_UNTUK VARCHAR2(4) UNIQUE CHECK (DEFAULT_UNTUK IN ('KAS','BANK')),
  AKTIF CHAR(1) DEFAULT 'Y' NOT NULL CHECK (AKTIF IN ('Y','T'))
)
/
CREATE TABLE MOB_KAS_MUTASI (
  ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  AKUN_ID NUMBER NOT NULL REFERENCES MOB_KAS_AKUN(ID),
  TANGGAL DATE NOT NULL,
  ARAH CHAR(1) NOT NULL CHECK (ARAH IN ('M','K')),
  NOMINAL NUMBER(16,0) NOT NULL CHECK (NOMINAL > 0),
  KETERANGAN VARCHAR2(250 CHAR) NOT NULL,
  SUMBER VARCHAR2(12) NOT NULL CHECK (SUMBER IN ('PENJUALAN','BELI_BAYAR','PINJAMAN','MANUAL','TRANSFER')),
  REF VARCHAR2(60),
  BALIK_ID NUMBER UNIQUE REFERENCES MOB_KAS_MUTASI(ID),
  USER_ID NUMBER,
  USER_NAMA VARCHAR2(100),
  CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
)
/
CREATE INDEX IX_MOB_KAS_MUTASI_AKUN ON MOB_KAS_MUTASI(AKUN_ID, TANGGAL, ID)
/
CREATE INDEX IX_MOB_KAS_MUTASI_REF ON MOB_KAS_MUTASI(SUMBER, REF)
