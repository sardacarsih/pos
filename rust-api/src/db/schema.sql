-- Skema khusus mobile (prefiks MOB_). Tidak menyentuh tabel desktop (POS_USER dll).
-- Statement dipisah baris "/". Idempotent: ORA-00955 (nama sudah ada) diabaikan oleh `migrate`.
CREATE TABLE MOB_USER (
  USER_ID              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  USERNAME             VARCHAR2(50)  NOT NULL,
  FULL_NAME            VARCHAR2(100),
  PASSWORD_HASH        VARCHAR2(255) NOT NULL,
  ROLE                 VARCHAR2(10)  NOT NULL,
  NIK                  VARCHAR2(30),
  IS_ACTIVE            NUMBER(1)     DEFAULT 1 NOT NULL,
  MUST_CHANGE_PASSWORD NUMBER(1)     DEFAULT 1 NOT NULL,
  FAILED_ATTEMPTS      NUMBER        DEFAULT 0 NOT NULL,
  LOCKED_UNTIL         TIMESTAMP,
  CREATED_AT           TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT UQ_MOB_USER_NAME UNIQUE (USERNAME),
  CONSTRAINT UQ_MOB_USER_NIK  UNIQUE (NIK),
  CONSTRAINT CK_MOB_USER_ROLE CHECK (ROLE IN ('KASIR','ADMIN','ANGGOTA')),
  CONSTRAINT CK_MOB_USER_NIK  CHECK (ROLE <> 'ANGGOTA' OR NIK IS NOT NULL)
)
/
CREATE TABLE MOB_SESSION (
  SESSION_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  FAMILY_ID  VARCHAR2(36) NOT NULL,
  USER_ID    NUMBER NOT NULL REFERENCES MOB_USER (USER_ID),
  TOKEN_HASH VARCHAR2(64) NOT NULL,
  DEVICE_ID  VARCHAR2(100),
  IP         VARCHAR2(45),
  CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  EXPIRES_AT TIMESTAMP NOT NULL,
  USED_AT    TIMESTAMP,
  REVOKED_AT TIMESTAMP,
  CONSTRAINT UQ_MOB_SESSION_HASH UNIQUE (TOKEN_HASH)
)
/
CREATE INDEX IX_MOB_SESSION_FAMILY ON MOB_SESSION (FAMILY_ID)
/
CREATE TABLE MOB_USER_KATEGORI (
  USER_ID     NUMBER NOT NULL REFERENCES MOB_USER (USER_ID),
  KATEGORI_ID VARCHAR2(30) NOT NULL,
  CONSTRAINT PK_MOB_USER_KATEGORI PRIMARY KEY (USER_ID, KATEGORI_ID)
)
/
-- Kategori yang tampil di Pilih Produk kasir (global; kosong = semua).
CREATE TABLE MOB_KATEGORI_TAMPIL (
  KATEGORI_ID VARCHAR2(30) PRIMARY KEY
)
/
-- Urutan manual produk di Pilih Produk kasir (kecil = di atas; tanpa baris = abjad di bawah).
CREATE TABLE MOB_PRODUK_URUT (
  PRODUCT_ID NUMBER PRIMARY KEY,
  URUT       NUMBER NOT NULL
)
/
-- Nomor transaksi yang diterbitkan ke kasir dan status faktur mobile.
CREATE TABLE MOB_NOMOR (
  NO_TRANSAKSI VARCHAR2(30) PRIMARY KEY,
  USER_ID      NUMBER NOT NULL REFERENCES MOB_USER (USER_ID),
  ISSUED_AT    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  USED_AT      TIMESTAMP
)
/
-- Kunci request checkout dipertahankan bersama nomor/faktur untuk retry dan recovery.
CREATE TABLE MOB_IDEMPOTENCY (
  USER_ID         NUMBER NOT NULL REFERENCES MOB_USER (USER_ID),
  OPERASI         VARCHAR2(20) NOT NULL,
  IDEMPOTENCY_KEY VARCHAR2(36) NOT NULL,
  RESOURCE_ID     VARCHAR2(30),
  PAYLOAD_HASH    VARCHAR2(64),
  CREATED_AT      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_MOB_IDEMPOTENCY PRIMARY KEY (USER_ID, OPERASI, IDEMPOTENCY_KEY)
)
/
-- Foto produk yang diunggah admin (BLOB, maks ~1 MB). Tabel terpisah: POS_PRODUCT (dipakai desktop) tidak diubah.
-- VERSI = epoch detik saat unggah; klien memakainya sebagai kunci cache dan penanda "ada foto".
CREATE TABLE MOB_PRODUK_FOTO (
  PRODUCT_ID   NUMBER NOT NULL,
  CONTENT_TYPE VARCHAR2(30) NOT NULL,
  DATA         BLOB NOT NULL,
  VERSI        NUMBER NOT NULL,
  CONSTRAINT PK_MOB_PRODUK_FOTO PRIMARY KEY (PRODUCT_ID)
)
/
-- Profil tambahan akun mobile (kontak + foto). Nama tampilan tetap di MOB_USER.FULL_NAME.
-- FOTO_VERSI = epoch detik saat unggah (kunci cache klien; null = tidak ada foto).
CREATE TABLE MOB_USER_PROFIL (
  USER_ID    NUMBER PRIMARY KEY REFERENCES MOB_USER (USER_ID),
  TELEPON    VARCHAR2(20),
  EMAIL      VARCHAR2(100),
  FOTO_TYPE  VARCHAR2(30),
  FOTO       BLOB,
  FOTO_VERSI NUMBER
)
/
CREATE TABLE MOB_PUSH_DEVICE (
  DEVICE_ID VARCHAR2(100) PRIMARY KEY,
  USER_ID NUMBER NOT NULL REFERENCES MOB_USER (USER_ID),
  TOKEN_HASH VARCHAR2(64) NOT NULL UNIQUE,
  TOKEN VARCHAR2(2048) NOT NULL,
  UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
)
/
CREATE TABLE MOB_PUSH_QUEUE (
  SALE_ID NUMBER PRIMARY KEY,
  NO_TRANSAKSI VARCHAR2(100) NOT NULL,
  NIK VARCHAR2(100) NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  NEXT_ATTEMPT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  LEASE_ID VARCHAR2(36),
  LEASE_UNTIL TIMESTAMP,
  ATTEMPTS NUMBER DEFAULT 0 NOT NULL,
  SENT_AT TIMESTAMP
)
/
CREATE INDEX IX_MOB_PUSH_QUEUE_PENDING ON MOB_PUSH_QUEUE (SENT_AT, NEXT_ATTEMPT)
/
CREATE OR REPLACE TRIGGER MOB_PUSH_SALE_INSERT
AFTER INSERT ON POS_PENJUALAN
FOR EACH ROW
WHEN (NEW.NIK IS NOT NULL AND NEW.NO_TRANSAKSI IS NOT NULL)
BEGIN
  INSERT INTO MOB_PUSH_QUEUE (SALE_ID, NO_TRANSAKSI, NIK)
  VALUES (:NEW.ID_PENJUALAN, :NEW.NO_TRANSAKSI, :NEW.NIK);
END;
