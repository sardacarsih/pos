-- Skema khusus mobile (prefiks MOB_). Tidak menyentuh tabel desktop (POS_USER dll).
-- Statement dipisah baris "/". Idempotent: ORA-00955 (nama sudah ada) diabaikan oleh `migrate`.
CREATE TABLE MOB_USER (
  USER_ID              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  USERNAME             VARCHAR2(50)  NOT NULL,
  FULL_NAME            VARCHAR2(100),
  PASSWORD_HASH        VARCHAR2(255) NOT NULL,
  ROLE                 VARCHAR2(10)  NOT NULL,
  NIK                  VARCHAR2(30),
  IS_ACTIVE            NUMBER(1)     DEFAULT 1 NOT NULL,
  MUST_CHANGE_PASSWORD NUMBER(1)     DEFAULT 1 NOT NULL,
  FAILED_ATTEMPTS      NUMBER        DEFAULT 0 NOT NULL,
  LOCKED_UNTIL         TIMESTAMP,
  CREATED_AT           TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT UQ_MOB_USER_NAME UNIQUE (USERNAME),
  CONSTRAINT UQ_MOB_USER_NIK  UNIQUE (NIK),
  CONSTRAINT CK_MOB_USER_ROLE CHECK (ROLE IN ('KASIR','ADMIN','ANGGOTA')),
  CONSTRAINT CK_MOB_USER_NIK  CHECK (ROLE <> 'ANGGOTA' OR NIK IS NOT NULL)
)
/
CREATE TABLE MOB_SESSION (
  SESSION_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  FAMILY_ID  VARCHAR2(36) NOT NULL,
  USER_ID    NUMBER NOT NULL REFERENCES MOB_USER (USER_ID),
  TOKEN_HASH VARCHAR2(64) NOT NULL,
  DEVICE_ID  VARCHAR2(100),
  IP         VARCHAR2(45),
  CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  EXPIRES_AT TIMESTAMP NOT NULL,
  USED_AT    TIMESTAMP,
  REVOKED_AT TIMESTAMP,
  CONSTRAINT UQ_MOB_SESSION_HASH UNIQUE (TOKEN_HASH)
)
/
CREATE INDEX IX_MOB_SESSION_FAMILY ON MOB_SESSION (FAMILY_ID)
/
CREATE TABLE MOB_USER_KATEGORI (
  USER_ID     NUMBER NOT NULL REFERENCES MOB_USER (USER_ID),
  KATEGORI_ID VARCHAR2(30) NOT NULL,
  CONSTRAINT PK_MOB_USER_KATEGORI PRIMARY KEY (USER_ID, KATEGORI_ID)
)
/
-- Nomor transaksi yang diterbitkan ke kasir; sekaligus kunci idempotensi simpan faktur.
CREATE TABLE MOB_NOMOR (
  NO_TRANSAKSI VARCHAR2(30) PRIMARY KEY,
  USER_ID      NUMBER NOT NULL REFERENCES MOB_USER (USER_ID),
  ISSUED_AT    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  USED_AT      TIMESTAMP
)
