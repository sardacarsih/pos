CREATE OR REPLACE TRIGGER MOB_BELI_HEADER_GUARD
BEFORE INSERT OR UPDATE OR DELETE ON POS_PEMBELIAN
FOR EACH ROW
DECLARE
  TERKUNCI NUMBER;
BEGIN
  SELECT COUNT(*) INTO TERKUNCI FROM MOB_BELI
  WHERE (NO_TRANSAKSI = :OLD.NO_TRANSAKSI OR NO_TRANSAKSI = :NEW.NO_TRANSAKSI
      OR PURCHASE_ID = :OLD.PURCHASE_ID OR PURCHASE_ID = :NEW.PURCHASE_ID)
    AND (BATAL_AT IS NULL OR :NEW.NO_TRANSAKSI IS NOT NULL);
  IF TERKUNCI > 0 THEN
    RAISE_APPLICATION_ERROR(-20081, 'Koreksi faktur ini melalui POS Web');
  END IF;
END;
/
