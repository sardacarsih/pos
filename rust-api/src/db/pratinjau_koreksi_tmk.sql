-- Baca saja. Gunakan sebelum menyetujui koreksi terhadap kejadian lama.
WITH terakhir AS (
  SELECT ID, ID_PELANGGAN, NIK, JENIS, WAKTU,
         ROW_NUMBER() OVER (PARTITION BY ID_PELANGGAN ORDER BY ID DESC) AS URUT
  FROM MOB_ANGGOTA_RIWAYAT
  WHERE JENIS IN ('BERHENTI', 'GABUNG_KEMBALI')
)
SELECT A.ID_PELANGGAN, A.NIK, R.ID AS ID_RIWAYAT,
       TO_CHAR(A.TMK, 'YYYY-MM-DD') AS TMK_TERSIMPAN,
       TO_CHAR(R.WAKTU, 'YYYY-MM-DD') AS TMK_TERVERIFIKASI,
       CASE
         WHEN A.TMK IS NULL OR TRUNC(A.TMK) < TRUNC(CAST(R.WAKTU AS DATE)) THEN 'USUL_KOREKSI'
         WHEN TRUNC(A.TMK) > TRUNC(CAST(R.WAKTU AS DATE)) THEN 'TINJAU_MANUAL'
         ELSE 'SUDAH_COCOK'
       END AS HASIL
FROM FIN_ANGGOTA A
JOIN terakhir R ON R.ID_PELANGGAN = A.ID_PELANGGAN AND R.NIK = A.NIK AND R.URUT = 1
WHERE A.ANGGOTA = 'Y' AND R.JENIS = 'GABUNG_KEMBALI'
ORDER BY A.NIK;
