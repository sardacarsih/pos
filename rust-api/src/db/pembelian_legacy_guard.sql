CREATE OR REPLACE TRIGGER MOB_BELI_LAMA_HEADER_GUARD
BEFORE INSERT OR UPDATE OR DELETE ON POS_PEMBELIAN
FOR EACH ROW
DECLARE
  TERKUNCI NUMBER;
BEGIN
  SELECT COUNT(*) INTO TERKUNCI FROM MOB_BELI_LAMA
  WHERE NO_TRANSAKSI IN (:OLD.NO_TRANSAKSI,:NEW.NO_TRANSAKSI)
     OR PURCHASE_ID IN (:OLD.PURCHASE_ID,:NEW.PURCHASE_ID);
  IF TERKUNCI > 0 THEN
    RAISE_APPLICATION_ERROR(-20082, 'Saldo faktur sudah terverifikasi. Koreksi saldo melalui POS Web');
  END IF;
END;
/
