CREATE TABLE MOB_PINJAMAN_AJU (
  ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  NIK VARCHAR2(30) NOT NULL,
  NAMA VARCHAR2(100 CHAR) NOT NULL,
  JUMLAH NUMBER(16,0) NOT NULL CHECK (JUMLAH > 0),
  TENOR NUMBER(3) NOT NULL CHECK (TENOR > 0),
  BUNGA NUMBER(6,3) NOT NULL,
  ANGSURAN NUMBER(16,2) NOT NULL,
  KEPERLUAN VARCHAR2(200 CHAR) NOT NULL,
  STATUS VARCHAR2(12) DEFAULT 'DIAJUKAN' NOT NULL
    CHECK (STATUS IN ('DIAJUKAN','DIVERIFIKASI','DISETUJUI','DICAIRKAN','DITOLAK','DIBATALKAN')),
  TGL_AJU TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  AJU_USER NUMBER NOT NULL,
  VERIF_USER NUMBER, VERIF_NAMA VARCHAR2(100), VERIF_TGL TIMESTAMP, VERIF_CATATAN VARCHAR2(200 CHAR),
  SETUJU_USER NUMBER, SETUJU_NAMA VARCHAR2(100), SETUJU_TGL TIMESTAMP, SETUJU_CATATAN VARCHAR2(200 CHAR),
  TOLAK_USER NUMBER, TOLAK_NAMA VARCHAR2(100), TOLAK_TGL TIMESTAMP, ALASAN VARCHAR2(200 CHAR),
  CAIR_USER NUMBER, CAIR_NAMA VARCHAR2(100), CAIR_TGL TIMESTAMP,
  NO_TRANSAKSI VARCHAR2(30) UNIQUE
)
/
-- Satu pengajuan berjalan per anggota.
CREATE UNIQUE INDEX UQ_MOB_PINJAMAN_AJU_JALAN ON MOB_PINJAMAN_AJU
  (CASE WHEN STATUS IN ('DIAJUKAN','DIVERIFIKASI','DISETUJUI') THEN NIK END)
/
CREATE INDEX IX_MOB_PINJAMAN_AJU_STATUS ON MOB_PINJAMAN_AJU (STATUS, SETUJU_TGL, ID)
/
CREATE INDEX IX_MOB_PINJAMAN_AJU_NIK ON MOB_PINJAMAN_AJU (NIK, ID)
/
-- Plafon dana pencairan per POS_PERIODE.PERIODE.
CREATE TABLE MOB_PINJAMAN_PLAFON (
  PERIODE NUMBER(6) PRIMARY KEY,
  PLAFON NUMBER(16,0) NOT NULL CHECK (PLAFON >= 0),
  DIUBAH_OLEH VARCHAR2(100),
  DIUBAH_TGL TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
)
/
CREATE TABLE MOB_PINJAMAN_HAK (
  USER_ID NUMBER NOT NULL REFERENCES MOB_USER (USER_ID),
  TAHAP VARCHAR2(10) NOT NULL CHECK (TAHAP IN ('VERIFIKASI','SETUJU','CAIR')),
  CONSTRAINT PK_MOB_PINJAMAN_HAK PRIMARY KEY (USER_ID, TAHAP)
)
