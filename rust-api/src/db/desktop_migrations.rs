const BUAT_TABEL_TRACKING: &str = "BEGIN\n  EXECUTE IMMEDIATE 'CREATE TABLE POS_SCHEMA_MIGRATION (\
MIGRATION_ID VARCHAR2(100) CONSTRAINT PK_POS_SCHEMA_MIGRATION PRIMARY KEY, \
CHECKSUM VARCHAR2(64), \
APPLIED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL)';\n\
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF;\nEND;";

/// Terapkan migrasi yang belum tercatat; kembalikan jumlah migrasi baru. Setiap migrasi tercatat setelah semua
/// statement-nya jalan, sehingga kegagalan di tengah aman diulang (statement idempotent).
pub fn jalankan(conn: &Connection, log: &mut impl FnMut(String)) -> AppResult<usize> {
    conn.execute(BUAT_TABEL_TRACKING, &[])?;
    let mut sudah: HashMap<String, Option<String>> = HashMap::new();
    for r in conn.query_as::<(String, Option<String>)>("SELECT MIGRATION_ID, CHECKSUM FROM POS_SCHEMA_MIGRATION", &[])? {
        let (id, cs) = r?;
        sudah.insert(id, cs);
    }

    let mut baru = 0;
    for m in semua() {
        let dikenal = checksums_dikenal(&m);
        if let Some(ada) = sudah.get(m.id) {
            match ada {
                Some(cs) if !dikenal.contains(cs) => {
                    log(format!("  [WARN ] {} sudah diterapkan, tapi definisi berubah (checksum beda).", m.id))
                }
                _ => log(format!("  [skip ] {}", m.id)),
            }
            continue;
        }
        log(format!("  [apply] {} - {}", m.id, m.deskripsi));
        for s in &m.statements {
            conn.execute(&render(s, false), &[])?;
        }
        conn.execute(
            "INSERT INTO POS_SCHEMA_MIGRATION (MIGRATION_ID, CHECKSUM) VALUES (:1, :2)",
            &[&m.id, &dikenal[0]],
        )?;
        conn.commit()?;
        baru += 1;
    }
    Ok(baru)
}

/// Buat user admin desktop dengan akses ADMIN ke semua app aktif. `false` bila username sudah ada.
pub fn seed_admin(conn: &Connection, username: &str, hash: &str) -> AppResult<bool> {
    let username = username.trim().to_lowercase();
    let ada: i64 = conn.query_row_as("SELECT COUNT(*) FROM POS_USER WHERE USERNAME = :1", &[&username])?;
    if ada > 0 {
        return Ok(false);
    }
    let role_id: i64 = super::opt(conn.query_row_as("SELECT ROLE_ID FROM POS_ROLE WHERE ROLE_NAME = 'ADMIN' AND IS_ACTIVE = 1", &[]))?
        .ok_or_else(|| AppError::Internal("Role 'ADMIN' tidak ada - jalankan migrasi terlebih dahulu".into()))?;
    conn.execute(
        "INSERT INTO POS_USER (USERNAME, FULL_NAME, PASSWORD_HASH) VALUES (:1, 'Administrator', :2)",
        &[&username, &hash],
    )?;
    let user_id: i64 = conn.query_row_as("SELECT USER_ID FROM POS_USER WHERE USERNAME = :1", &[&username])?;
    conn.execute(
        "INSERT INTO POS_USER_ACCESS (USER_ID, APP_ID, ROLE_ID, IS_ACTIVE) SELECT :1, APP_ID, :2, 1 FROM POS_APP WHERE IS_ACTIVE = 1",
        &[&user_id, &role_id],
    )?;
    conn.commit()?;
    Ok(true)
}

/// Reset password user desktop sekaligus mengaktifkan dan membuka kunci akun. `false` bila user tidak ada.
pub fn reset_admin(conn: &Connection, username: &str, hash: &str) -> AppResult<bool> {
    let n = conn
        .execute(
            "UPDATE POS_USER SET PASSWORD_HASH = :1, IS_ACTIVE = 1, IS_LOCKED = 0, FAILED_ATTEMPTS = 0, UPDATED_AT = SYSTIMESTAMP \
             WHERE USERNAME = :2",
            &[&hash, &username.trim().to_lowercase()],
        )?
        .row_count()?;
    conn.commit()?;
    Ok(n > 0)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn id_unik_dan_berurutan() {
        let ids: Vec<_> = semua().iter().map(|m| m.id).collect();
        let mut urut = ids.clone();
        urut.sort();
        urut.dedup();
        assert_eq!(ids, urut);
        assert_eq!(ids.len(), 13);
    }

    #[test]
    fn checksum_hex_besar_64_karakter() {
        let c = checksum("x", &["a".into()]);
        assert_eq!(c.len(), 64);
        assert_eq!(c, c.to_uppercase());
        // SHA-256("x\na")
        assert_eq!(c, checksum("x", &["a".to_string()]));
        assert_ne!(c, checksum("x", &["b".to_string()]));
    }

    #[test]
    fn ddl_dibungkus_dan_kutip_di_escape() {
        let t = render(&Stmt::Ddl("CREATE TABLE T (C VARCHAR2(1) DEFAULT 'x')".into()), false);
        assert!(t.starts_with("BEGIN\n   EXECUTE IMMEDIATE 'CREATE TABLE T"));
        assert!(t.contains("DEFAULT ''x'')';"));
        assert!(t.ends_with("END;"));
    }

    #[test]
    fn varian_crlf_hanya_mengubah_isi_multibaris() {
        let m = &semua()[3]; // 0004: satu baris -> kedua varian identik
        let [lf, crlf] = checksums_dikenal(m);
        assert_eq!(lf, crlf);
        let m = &semua()[0]; // 0001: multibaris -> beda
        let [lf, crlf] = checksums_dikenal(m);
        assert_ne!(lf, crlf);
    }
}
