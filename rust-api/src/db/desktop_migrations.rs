//! Migrasi skema desktop (login/RBAC POS_*, dll), port dari `Migrator/Migrations.cs` (C#) yang sudah dihapus.
//! Forward-only: tambah entri BARU di akhir `semua()` dengan id berprefiks angka; jangan ubah entri lama
//! (checksum tersimpan di `POS_SCHEMA_MIGRATION`). DDL dibungkus `Stmt::Ddl` agar idempotent.
use std::collections::HashMap;

use oracle::Connection;
use sha2::{Digest, Sha256};

use crate::error::{AppError, AppResult};

pub enum Stmt {
    /// DDL; error "objek sudah ada" ditelan (ORA-00955/-01408/-01430/-02260/-02275).
    Ddl(String),
    /// SQL/PLSQL apa adanya.
    Raw(String),
}

pub struct Migration {
    pub id: &'static str,
    pub deskripsi: &'static str,
    pub statements: Vec<Stmt>,
}

fn seed_app(id: &str, nama: &str) -> String {
    format!(
        "INSERT INTO POS_APP (APP_ID, APP_NAME, IS_ACTIVE) SELECT '{id}', '{nama}', 1 FROM DUAL \
         WHERE NOT EXISTS (SELECT 1 FROM POS_APP WHERE APP_ID = '{id}')"
    )
}

fn seed_role(nama: &str) -> String {
    format!(
        "INSERT INTO POS_ROLE (ROLE_NAME) SELECT '{nama}' FROM DUAL \
         WHERE NOT EXISTS (SELECT 1 FROM POS_ROLE WHERE ROLE_NAME = '{nama}')"
    )
}

/// Teks statement siap eksekusi. `crlf` hanya untuk menghitung checksum varian lama (C# mengompilasi
/// string multi-baris dengan CRLF di Windows); pembungkus DDL selalu LF seperti di C#.
fn render(s: &Stmt, crlf: bool) -> String {
    let norm = |t: &str| {
        let lf = t.replace("\r\n", "\n");
        if crlf { lf.replace('\n', "\r\n") } else { lf }
    };
    match s {
        Stmt::Raw(t) => norm(t),
        Stmt::Ddl(t) => format!(
            "BEGIN\n   EXECUTE IMMEDIATE '{}';\nEXCEPTION WHEN OTHERS THEN\n   \
             IF SQLCODE NOT IN (-955, -1408, -1430, -2260, -2275) THEN RAISE; END IF;\nEND;",
            norm(t).replace('\'', "''").trim()
        ),
    }
}

/// SHA-256 hex huruf besar atas `id` + ("\n" + statement)*, sama dengan `MigrationRunner.Checksum` di C#.
pub fn checksum(id: &str, teks: &[String]) -> String {
    let mut h = Sha256::new();
    h.update(id.as_bytes());
    for t in teks {
        h.update(b"\n");
        h.update(t.as_bytes());
    }
    h.finalize().iter().map(|b| format!("{b:02X}")).collect()
}

fn checksums_dikenal(m: &Migration) -> [String; 2] {
    [false, true].map(|crlf| {
        let teks: Vec<String> = m.statements.iter().map(|s| render(s, crlf)).collect();
        checksum(m.id, &teks)
    })
}

