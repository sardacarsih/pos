CREATE TABLE MOB_BELI (
  NO_TRANSAKSI VARCHAR2(30) PRIMARY KEY,
  PURCHASE_ID NUMBER NOT NULL UNIQUE,
  SUPPLIER_ID VARCHAR2(50) NOT NULL,
  SUPPLIER_NAMA VARCHAR2(200) NOT NULL,
  NO_FAKTUR VARCHAR2(100 CHAR) NOT NULL,
  TANGGAL_FAKTUR DATE NOT NULL,
  TANGGAL_TERIMA DATE NOT NULL,
  JATUH_TEMPO DATE,
  JENIS VARCHAR2(5) NOT NULL CHECK (JENIS IN ('TUNAI', 'TEMPO')),
  BRUTO NUMBER(16,0) NOT NULL,
  POTONGAN NUMBER(16,0) NOT NULL,
  TOTAL NUMBER(16,0) NOT NULL,
  USER_ID NUMBER NOT NULL REFERENCES MOB_USER(USER_ID),
  USER_NAMA VARCHAR2(100) NOT NULL,
  POSTED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  BATAL_AT TIMESTAMP,
  BATAL_USER NUMBER REFERENCES MOB_USER(USER_ID),
  BATAL_NAMA VARCHAR2(100),
  BATAL_ALASAN VARCHAR2(250 CHAR)
)
/
CREATE UNIQUE INDEX UX_MOB_BELI_FAKTUR ON MOB_BELI (
  CASE WHEN BATAL_AT IS NULL THEN SUPPLIER_ID END,
  CASE WHEN BATAL_AT IS NULL THEN UPPER(TRIM(NO_FAKTUR)) END
)
/
CREATE INDEX IX_MOB_BELI_TERIMA ON MOB_BELI(TANGGAL_TERIMA, NO_TRANSAKSI)
/
CREATE INDEX IX_MOB_BELI_USER ON MOB_BELI(USER_ID, TANGGAL_TERIMA)
/
CREATE TABLE MOB_BELI_BARIS (
  NO_TRANSAKSI VARCHAR2(30) NOT NULL REFERENCES MOB_BELI(NO_TRANSAKSI),
  BARIS NUMBER NOT NULL,
  PRODUCT_ID NUMBER NOT NULL,
  KODE_BARANG VARCHAR2(30) NOT NULL,
  NAMA_BARANG VARCHAR2(200) NOT NULL,
  SATUAN VARCHAR2(20) NOT NULL,
  SATUAN_DASAR VARCHAR2(20) NOT NULL,
  ISI NUMBER NOT NULL,
  QTY NUMBER NOT NULL,
  HARGA NUMBER(16,0) NOT NULL,
  POTONGAN NUMBER(16,0) NOT NULL,
  CONSTRAINT PK_MOB_BELI_BARIS PRIMARY KEY (NO_TRANSAKSI, BARIS)
)
/
CREATE TABLE MOB_BELI_BAYAR (
  ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  NO_TRANSAKSI VARCHAR2(30) NOT NULL REFERENCES MOB_BELI(NO_TRANSAKSI),
  TANGGAL DATE NOT NULL,
  METODE VARCHAR2(10) NOT NULL CHECK (METODE IN ('TUNAI','TRANSFER','LAINNYA')),
  REFERENSI VARCHAR2(100 CHAR),
  NOMINAL NUMBER(16,0) NOT NULL,
  BALIK_ID NUMBER UNIQUE REFERENCES MOB_BELI_BAYAR(ID),
  ALASAN VARCHAR2(250 CHAR),
  USER_ID NUMBER NOT NULL REFERENCES MOB_USER(USER_ID),
  USER_NAMA VARCHAR2(100) NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT CK_MOB_BELI_BAYAR CHECK (
    (BALIK_ID IS NULL AND NOMINAL > 0) OR
    (BALIK_ID IS NOT NULL AND NOMINAL < 0 AND ALASAN IS NOT NULL)
  )
)
/
CREATE INDEX IX_MOB_BELI_BAYAR_NO ON MOB_BELI_BAYAR(NO_TRANSAKSI, ID)
/
CREATE TABLE MOB_BELI_NOMOR (
  TAHUN NUMBER(4) PRIMARY KEY,
  NOMOR NUMBER(6) NOT NULL
)
